/**
 * Returns all 36 States and Union Territories.
 */
export function getAllStates(): StateData[] {
  return INDIA_STATES_DATA;
}

/**
 * Returns only the 28 States of India.
 */
export function getOnlyStates(): StateData[] {
  return INDIA_STATES_DATA.filter((item) => item.type === 'state');
}

/**
 * Returns only the 8 Union Territories of India.
 */
export function getOnlyUnionTerritories(): StateData[] {
  return INDIA_STATES_DATA.filter((item) => item.type === 'union-territory');
}

/**
 * Retrieves a state or Union Territory by its unique slug ID (case-insensitive).
 * Example: getStateById('rajasthan') or getStateById('delhi')
 */
export function getStateById(id: string): StateData | undefined {
  if (!id) return undefined;
  const normalizedId = id.trim().toLowerCase();
  const found = INDIA_STATES_DATA.find((item) => item.id.toLowerCase() === normalizedId);
  if (!found) return undefined;

  const gallery = getStateGallery(found.id, found.name, found.region);
  return {
    ...found,
    heroImage: found.heroImage || gallery.heroImage.url,
    gallery,
  };
}

/**
 * Retrieves all states and UTs belonging to a specific geographical region.
 * Region options: 'North' | 'South' | 'East' | 'West' | 'Central' | 'Northeast' | 'Islands'
 */
export function getStatesByRegion(region: IndianRegion): StateData[] {
  return INDIA_STATES_DATA.filter((item) => item.region.toLowerCase() === region.toLowerCase());
}

/**
 * Searches states and Union Territories using state-level metadata plus
 * explicitly authored culture, festival and place records.
 * Raw category arrays are intentionally not stored on StateData.
 */
export function searchStates(query: string): StateData[] {
  if (!query || query.trim() === '') return INDIA_STATES_DATA;
  const q = query.toLowerCase().trim();

  const matchingStateIds = new Set<string>();
  ALL_CULTURE_DATA.forEach((item) => {
    if (item.name.toLowerCase().includes(q) || item.shortDescription.toLowerCase().includes(q)) {
      matchingStateIds.add(item.stateId);
    }
  });
  FESTIVALS_DATA.forEach((festival) => {
    if (festival.name.toLowerCase().includes(q) || festival.shortDescription.toLowerCase().includes(q)) {
      festival.primaryStates.forEach((state) => matchingStateIds.add(state.id));
    }
  });
  PLACES_DATA.forEach((place) => {
    if (place.name.toLowerCase().includes(q) || place.shortDescription.toLowerCase().includes(q)) {
      matchingStateIds.add(place.stateId);
    }
  });

  return INDIA_STATES_DATA.filter((item) => {
    return (
      item.name.toLowerCase().includes(q) ||
      (item.hindiName && item.hindiName.includes(q)) ||
      item.capital.toLowerCase().includes(q) ||
      item.tagline.toLowerCase().includes(q) ||
      item.region.toLowerCase().includes(q) ||
      item.languages.some((lang) => lang.toLowerCase().includes(q)) ||
      matchingStateIds.has(item.id)
    );
  });
}

/**
 * Returns a list of all unique geographic regions.
 */
export function getAllRegions(): IndianRegion[] {
  return ['North', 'South', 'East', 'West', 'Central', 'Northeast', 'Islands'];
}

/**
 * Retrieves the chronologically previous and next states relative to the given state id.
 */
export function getPreviousAndNextState(currentId: string): { prev: StateData; next: StateData } | undefined {
  if (!currentId) return undefined;
  const normalizedId = currentId.trim().toLowerCase();
  const index = INDIA_STATES_DATA.findIndex((item) => item.id.toLowerCase() === normalizedId);
  if (index === -1) return undefined;

  const prevIndex = (index - 1 + INDIA_STATES_DATA.length) % INDIA_STATES_DATA.length;
  const nextIndex = (index + 1) % INDIA_STATES_DATA.length;

  return {
    prev: INDIA_STATES_DATA[prevIndex],
    next: INDIA_STATES_DATA[nextIndex],
  };
}
